#!/usr/bin/env bash
# MirvkBuntu — authoritative build/output base configuration.
# Single path contract for Make/build/installer artifacts.

set -u

MIRVKBUNTU_REPO_ROOT="${MIRVKBUNTU_REPO_ROOT:-$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)}"

MIRVKBUNTU_BUILD_ROOT="${MIRVKBUNTU_BUILD_ROOT:-${MIRVKBUNTU_REPO_ROOT}/build/work}"
MIRVKBUNTU_OUTPUT_ROOT="${MIRVKBUNTU_OUTPUT_ROOT:-${MIRVKBUNTU_REPO_ROOT}/build/output}"
MIRVKBUNTU_INSTALLER_BUILD_ROOT="${MIRVKBUNTU_INSTALLER_BUILD_ROOT:-${MIRVKBUNTU_REPO_ROOT}/build/installer}"
MIRVKBUNTU_BUILDER_BUILD_ROOT="${MIRVKBUNTU_BUILDER_BUILD_ROOT:-${MIRVKBUNTU_REPO_ROOT}/build/builder}"

MIRVKBUNTU_OUTPUT_LINK="${MIRVKBUNTU_OUTPUT_LINK:-${MIRVKBUNTU_REPO_ROOT}/output}"
MIRVKBUNTU_DESKTOP_OUTPUT="${MIRVKBUNTU_DESKTOP_OUTPUT:-${HOME}/Desktop}"
MIRVKBUNTU_INSTALLER_OUTPUT_ROOT="${MIRVKBUNTU_INSTALLER_OUTPUT_ROOT:-${MIRVKBUNTU_OUTPUT_ROOT}/installer}"
MIRVKBUNTU_BUILDER_OUTPUT_ROOT="${MIRVKBUNTU_BUILDER_OUTPUT_ROOT:-${MIRVKBUNTU_OUTPUT_ROOT}/builder}"

MIRVKBUNTU_SLIM_ISO="${MIRVKBUNTU_OUTPUT_ROOT}/MirvkBuntu-slim-amd64.iso"
MIRVKBUNTU_MINIMUM_ISO="${MIRVKBUNTU_OUTPUT_ROOT}/MirvkBuntu-minimal-amd64.iso"
MIRVKBUNTU_FULL_ISO="${MIRVKBUNTU_OUTPUT_ROOT}/MirvkBuntu-desktop-amd64.iso"

MIRVKBUNTU_INSTALLER_BINARY="${MIRVKBUNTU_INSTALLER_OUTPUT_ROOT}/mirvkbuntu-installer"
MIRVKBUNTU_INSTALLER_WINDOWS_EXE="${MIRVKBUNTU_INSTALLER_OUTPUT_ROOT}/mirvkbuntu-installer.exe"
MIRVKBUNTU_INSTALLER_PACKAGES="${MIRVKBUNTU_INSTALLER_OUTPUT_ROOT}/packages"

MIRVKBUNTU_BUILDER_BINARY="${MIRVKBUNTU_BUILDER_OUTPUT_ROOT}/mirvkbuntu-builder"
MIRVKBUNTU_BUILDER_WINDOWS_EXE="${MIRVKBUNTU_BUILDER_OUTPUT_ROOT}/mirvkbuntu-builder.exe"

MIRVKBUNTU_UBUNTU_SUITE="${MIRVKBUNTU_UBUNTU_SUITE:-noble}"
MIRVKBUNTU_ARCH="${MIRVKBUNTU_ARCH:-amd64}"
MIRVKBUNTU_ISO_LABEL="${MIRVKBUNTU_ISO_LABEL:-MIRVKBUNTU}"

# Make/build target contract:
# make health       -> validation only; no release artifact
# make slim         -> MIRVKBUNTU_SLIM_ISO
# make minimal      -> MIRVKBUNTU_MINIMUM_ISO
# make full         -> MIRVKBUNTU_FULL_ISO
# make all-profiles -> all three ISO paths above
# make installer    -> installer binary + packages under MIRVKBUNTU_INSTALLER_OUTPUT_ROOT
# make builder      -> builder binary under MIRVKBUNTU_BUILDER_OUTPUT_ROOT
